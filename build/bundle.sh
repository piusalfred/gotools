# Assemble the single-file distributable gotools.sh from lib/ modules.
# gotools.sh is consumed as ONE file by install.sh, self-update, the release
# workflow, and the Go embed (gotools.go) — so lib/ is bundled at build time
# rather than sourced at runtime. Edit lib/, never gotools.sh directly.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

out="gotools.sh"
tmp="$out.tmp.$$"
trap 'rm -f "$tmp"' EXIT

{
    printf '#!/usr/bin/env bash\n'
    printf '# Copyright (c) 2026 Pius Alfred\n# License: MIT\n\n'
    printf '# ---------------------------------------------------------------------------\n'
    printf '# AUTOGENERATED FILE — DO NOT EDIT.\n'
    printf '# Assembled from lib/ modules by build/bundle.sh.\n'
    printf '# Make changes in lib/ and run: make bundle\n'
    printf '# ---------------------------------------------------------------------------\n\n'
    printf 'set -euo pipefail\n\n'
    # Each module's first 3 lines are its license header
    # (copyright, license, blank) — dropped when concatenating.
    # Commands are sorted explicitly so the bundle is identical across
    # platforms regardless of the shell's glob/locale ordering.
    for f in lib/config.sh lib/core.sh lib/manifest.sh lib/modparser.sh \
             lib/strategy.sh lib/help.sh $(printf '%s\n' lib/commands/*.sh | sort) lib/main.sh; do
        tail -n +4 "$f"
    done
} > "$tmp"
mv "$tmp" "$out"
chmod +x "$out"
echo "✅ bundled $out from lib/"
